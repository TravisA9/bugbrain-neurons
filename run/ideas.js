'use strict';
/* run/ideas.js (R38): experiments/ideas.json -> IDEAS.md (idea map + ranked open questions) and results/ideas.js (window.BB_IDEAS,
 * for dashboard.html's Ideas tab on file://). Payoff = impact (1-5) x likelihood (0-1) / cost (1-3). node run/ideas.js */
const fs = require('fs'), path = require('path'), ROOT = path.resolve(__dirname, '..');
const D = JSON.parse(fs.readFileSync(path.join(ROOT, 'experiments', 'ideas.json'), 'utf8'));
const payoff = q => +(q.impact * q.likelihood / q.cost).toFixed(2);
const Q = D.questions.map(q => Object.assign({ payoff: payoff(q) }, q)).sort((a, b) => b.payoff - a.payoff);
const esc = s => String(s).replace(/\|/g, '\\|');
const L = ['# BugBrain idea map (generated by run/ideas.js from experiments/ideas.json; edit the JSON, then rerun)', '',
  'Status: **adopted** (in the defaults), **rejected** (tested, no gain), **open** (not yet answered), **parked** (promising, set aside).',
  'Evidence is from RESULTS.md (round ids), results_box/R31_NOTES.md (R31-R33) and the legacy notes.', '',
  '| id | area | idea | status | key evidence | why | rounds |', '|---|---|---|---|---|---|---|'];
for (const i of D.ideas) L.push(`| ${i.id} | ${i.area} | ${esc(i.title)} | **${i.status}** | ${esc(i.evidence)} | ${esc(i.why)} | ${i.rounds.join(', ')} |`);
const cnt = {}; for (const i of D.ideas) cnt[i.status] = (cnt[i.status] || 0) + 1;
L.push('', 'Counts: ' + Object.entries(cnt).map(([k, v]) => `${k} ${v}`).join(', '), '',
  '## Open questions, ranked by expected payoff (impact x likelihood / cost)', '',
  '| rank | id | question | impact | likelihood | cost | payoff | experiment |', '|---|---|---|---|---|---|---|---|');
Q.forEach((q, k) => L.push(`| ${k + 1} | ${q.id} | ${esc(q.q)} | ${q.impact} | ${q.likelihood} | ${q.cost} | **${q.payoff}** | ${esc(q.experiment)} |`));
L.push('', 'Jobs that answer these questions live in experiments/queue/*.json (run/queue.js).', '');
fs.writeFileSync(path.join(ROOT, 'IDEAS.md'), L.join('\n'));
fs.mkdirSync(path.join(ROOT, 'results'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'results', 'ideas.js'), 'window.BB_IDEAS = ' + JSON.stringify({ ideas: D.ideas, questions: Q, writtenAt: new Date().toISOString() }) + ';\n');
console.log(`IDEAS.md: ${D.ideas.length} ideas, ${Q.length} open questions; top: ${Q.slice(0, 5).map(q => q.id + ' ' + q.payoff).join(', ')}`);
